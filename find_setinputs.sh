#!/bin/bash

FILE="public/js/app.js"

if [ ! -f "$FILE" ]; then
    echo -e "\n\033[1;31m=========================================="
    echo -e " ОШИБКА: Файл $FILE не найден!"
    echo -e "==========================================\033[0m\n"
    exit 1
fi

echo "=========================================="
echo " ПОИСК ФУНКЦИИ SETINPUTS В APP.JS"
echo "=========================================="
echo ""

# Ищем где объявлена функция setInputs
grep -n -C 20 "function setInputs" "$FILE"

if [ $? -ne 0 ]; then
    echo -e "\n\033[1;31m=========================================="
    echo -e " ВНИМАНИЕ: Функция setInputs не найдена!"
    echo -e "==========================================\033[0m\n"
fi

echo ""
echo "=========================================="
echo " КОНЕЦ ПОИСКА. Скопируй текст выше и отправь мне."
echo "=========================================="
