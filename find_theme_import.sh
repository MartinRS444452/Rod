#!/bin/bash

FILE="public/js/app.js"

if [ ! -f "$FILE" ]; then
    echo -e "\n\033[1;31m=========================================="
    echo -e " ОШИБКА: Файл $FILE не найден!"
    echo -e "==========================================\033[0m\n"
    exit 1
fi

echo "=========================================="
echo " ПОИСК КОДА ИМПОРТА ТЕМЫ В APP.JS"
echo "=========================================="
echo ""

# Ищем функцию обработки импорта темы (кнопку btn-apply-import)
grep -n -C 20 "btn-apply-import" "$FILE"

if [ $? -ne 0 ]; then
    echo -e "\n\033[1;31m=========================================="
    echo -e " ВНИМАНИЕ: Участок кода с импортом тем не найден!"
    echo -e "==========================================\033[0m\n"
fi

echo ""
echo "=========================================="
echo " КОНЕЦ ПОИСКА. Скопируй текст выше и отправь мне."
echo "=========================================="
